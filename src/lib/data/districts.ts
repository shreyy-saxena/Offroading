// Maps API, not assumed).
//
// Known residual risk, same caveat the original seed already carried:
// India periodically renames, splits, and merges districts, so this list
// will drift out of date again — re-verify against an authoritative
// source (e.g. the Ministry of Panchayati Raj's Local Government
// Directory codes) periodically, and treat a "not a recognized district"
